def set_run_font(run, font_name, size, bold=False):
    run.font.name = font_name
    run._element.rPr.rFonts.set(qn('w:eastAsia'), font_name)
    run.font.size = size
    run.font.bold = bold


def add_heading_styled(text, level=1, font_name='黑体', size=None,
                       bold=True, alignment=WD_ALIGN_PARAGRAPH.LEFT,
                       space_before=Pt(12), space_after=Pt(6)):
    if size is None:
        size_map = {0: Pt(22), 1: Pt(16), 2: Pt(14), 3: Pt(13)}
        size = size_map.get(level, Pt(12))
    p = doc.add_paragraph()
    p.alignment = alignment
    p.paragraph_format.line_spacing = 1.5
    p.paragraph_format.space_before = space_before
    p.paragraph_format.space_after = space_after
    r = p.add_run(text)
    set_run_font(r, font_name, size, bold)
    return p


